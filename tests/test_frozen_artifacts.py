"""Released run artifacts, read by the current readers (#271, persisted contracts D).

The documents under ``fixtures/persisted/artifacts/<release>/`` were written by
that release's own code (see ``freeze.py`` there) and are never regenerated by
the current writer. A current-writer test cannot notice a reader that stopped
accepting an old shape; these can.

Only the machine-bound values ``bindings.json`` names are rebound to this test's
repository: the repo root, and the source fingerprint, recomputed in the stored
value's own version. Every other byte is the release's.
"""

from __future__ import annotations

import json
import os
import shutil
import stat
import subprocess
from pathlib import Path

import pytest
from click.testing import CliRunner
from conftest import FakeMemory

from syncmill.artifacts import ArtifactStore
from syncmill.cli import cli
from syncmill.tui import _read_artifact_result, render_artifact
from syncmill.worktree import fingerprint_version, repository_fingerprint

FROZEN = Path(__file__).parent / "fixtures" / "persisted" / "artifacts"
RELEASES = sorted(p.name for p in FROZEN.iterdir() if p.is_dir())

#: scenario -> the state the release left it in
STATES = {
    "pending": "pending",
    "closed": "pending",
    "continued": "pending",
    "failed": "failed",
    "no_changes": "no_changes",
    "discarded": "discarded",
    "superseded": "superseded",
    "running": "running",
    "recovery_required": "recovery_required",
    "applying_unreceipted": "applying",
    "applying_receipted": "applying",
    "applied": "applied",
}
FIXED = "def add(a, b):\n    return a + b\n"


def test_every_release_freezes_every_scenario():
    # A release directory that lost a scenario would silently shrink coverage.
    assert RELEASES == ["v0.1.2", "v0.3.0"]
    for release in RELEASES:
        bindings = json.loads((FROZEN / release / "bindings.json").read_text())
        assert sorted(bindings["runs"]) == sorted(STATES)
        for scenario, state in STATES.items():
            manifest = json.loads((FROZEN / release / scenario / "manifest.json").read_text())
            assert manifest["state"] == state
            assert manifest["run_id"] == bindings["runs"][scenario]["run_id"]
            assert fingerprint_version(manifest["source_fingerprint"]) == 1


class Frozen:
    """One release's documents installed into a store bound to ``repo``."""

    def __init__(self, release: str, tmp_path: Path, monkeypatch):
        self.dir = FROZEN / release
        self.bindings = json.loads((self.dir / "bindings.json").read_text())
        self.repo = (tmp_path / "repo").resolve()
        self.repo.mkdir()
        for name, text in self.bindings["tree"].items():
            (self.repo / name).write_text(text, encoding="utf-8")
        for argv in (
            ["init", "-q"],
            ["add", "-A"],
            ["-c", "user.name=t", "-c", "user.email=t@t.test", "-c",
             "commit.gpgsign=false", "commit", "-q", "-m", "frozen tree"],
        ):
            subprocess.run(["git", *argv], cwd=self.repo, check=True, capture_output=True)
        self.runs_root = tmp_path / "state" / "runs"
        self.project = self.bindings["project_id"]
        monkeypatch.setenv("SYNCMILL_RUNS__ROOT", str(self.runs_root))
        monkeypatch.setenv("SYNCMILL_PROJECT__ID", self.project)
        monkeypatch.setenv("SYNCMILL_WORKSPACE__ROOT", str(tmp_path / "state" / "ws"))
        self.store = ArtifactStore(self.runs_root, self.project)

    def run_id(self, scenario: str) -> str:
        return self.bindings["runs"][scenario]["run_id"]

    def install(self, *scenarios: str) -> None:
        """Copy scenarios in, rebinding repo root and fingerprint by exact bytes."""
        for scenario in scenarios:
            stored_fp = self.bindings["runs"][scenario]["source_fingerprint"]
            live_fp = repository_fingerprint(self.repo, like=stored_fp)
            assert fingerprint_version(live_fp) == 1
            target = self.store.root / self.run_id(scenario)
            shutil.copytree(self.dir / scenario, target)
            for path in [target / "manifest.json", *target.glob("applications/*.json")]:
                data = path.read_bytes()
                root = self.bindings["repo_root"].encode()
                assert data.count(root) == 1, path
                data = data.replace(root, str(self.repo).encode())
                if path.name == "manifest.json":
                    assert data.count(stored_fp.encode()) == 1, path
                    data = data.replace(stored_fp.encode(), live_fp.encode())
                path.write_bytes(data)

    def stored(self, scenario: str, name: str = "manifest.json") -> dict:
        """The installed document: the release's, with machine values rebound."""
        return json.loads((self.store.root / self.run_id(scenario) / name).read_bytes())

    def frozen_bytes(self, scenario: str, name: str) -> bytes:
        return (self.dir / scenario / name).read_bytes()

    def cli(self, *argv: str):
        return CliRunner().invoke(cli, [*argv, "--repo", str(self.repo)])


@pytest.fixture(params=RELEASES)
def frozen(request, tmp_path, monkeypatch) -> Frozen:
    return Frozen(request.param, tmp_path, monkeypatch)


def _changed(before: dict, after: dict) -> set[str]:
    """Keys the release wrote whose values are no longer as written."""
    return {key for key in before if after.get(key, object()) != before[key]}


# ── listing and inspection ────────────────────────────────────────────────


def test_runs_list_and_show_read_every_released_state(frozen):
    frozen.install(*STATES)
    listed = frozen.cli("runs", "list")
    assert listed.exit_code == 0, listed.output
    assert "could not be read" not in listed.output
    rows = {line.split()[0]: line.split()[1] for line in listed.output.splitlines()}
    assert rows == {frozen.run_id(s): state for s, state in STATES.items()}
    for scenario in STATES:
        shown = frozen.cli("runs", "show", frozen.run_id(scenario))
        assert shown.exit_code == 0, shown.output
        assert json.loads(shown.output) == frozen.stored(scenario)


def test_released_conversations_are_listed_and_shown_as_recorded(frozen):
    frozen.install(*STATES)
    listed = frozen.cli("conversations", "list")
    assert listed.exit_code == 0, listed.output
    rows = {tuple(line.split()) for line in listed.output.splitlines()}
    with_session = {
        s for s in STATES if frozen.stored(s).get("provider_session_id")
    }
    assert with_session == set(STATES) - {"failed", "running", "recovery_required"}
    assert rows == {
        (frozen.run_id(s), "closed" if s == "closed" else "open", "codex",
         "fake-codex-thread")
        for s in with_session
    }
    # No release before failure_kind wrote it; result.json carries no such key.
    for scenario in ("pending", "failed"):
        result = frozen.stored(scenario, "result.json")
        assert "failure_kind" not in result
        shown = frozen.cli("conversations", "show", frozen.run_id(scenario))
        assert shown.exit_code == 0, shown.output
        assert json.loads(shown.output) == {
            "manifest": frozen.stored(scenario),
            "result": result,
        }


def _header(rendered: str) -> dict[str, str]:
    head = rendered.split("\n\n", 1)[0]
    return dict(line.split(": ", 1) for line in head.splitlines())


def test_the_tui_renders_every_field_of_every_released_run(frozen):
    frozen.install(*STATES)
    for scenario in STATES:
        run_id = frozen.run_id(scenario)
        manifest = frozen.stored(scenario)
        result = _read_artifact_result(run_id, store=frozen.store)
        rendered = render_artifact(frozen.store.load(run_id).manifest, result)
        expected = {
            "Run": run_id,
            "State": STATES[scenario],
            "Strategy": f"route | agent: {manifest.get('agent_id')}",
            "Created": manifest["created_at"],
            "Patch": f"{manifest.get('patch_bytes')} bytes {manifest.get('patch_sha256')}",
            "Files": ", ".join(manifest.get("files_changed") or []) or "-",
        }
        if scenario in ("running", "recovery_required"):
            # Interrupted before save: no result sidecar, no patch fields.
            assert result is None
            assert "patch_sha256" not in manifest
            assert rendered.endswith("\n\n(no result recorded)")
            if scenario == "recovery_required":
                # The release recorded str(KeyboardInterrupt()), which is "".
                assert manifest["recovery_reason"] == ""
            assert _header(rendered) == expected
            continue
        assert result == frozen.stored(scenario, "result.json")
        assert _header(rendered) == expected
        body = (
            f"Result: {result['status']} | exit: {result['exit_code']} | "
            f"{result['duration_seconds']}s"
        )
        if result["error"]:
            body += f"\nError: {result['error']}"
        if result["output"]:
            body += f"\n\n{result['output']}"
        assert rendered.split("\n\n", 1)[1] == body


def test_diff_prints_the_released_patch_byte_for_byte(frozen):
    frozen.install("pending", "continued")
    for scenario in ("pending", "continued"):
        shown = frozen.cli("diff", frozen.run_id(scenario))
        assert shown.exit_code == 0, shown.output
        assert shown.stdout_bytes == frozen.frozen_bytes(scenario, "winner.patch")


# ── apply ─────────────────────────────────────────────────────────────────


@pytest.mark.parametrize("scenario", ["pending", "closed", "continued"])
def test_a_released_pending_run_applies(frozen, scenario):
    frozen.install(scenario)
    run_id = frozen.run_id(scenario)
    before = frozen.stored(scenario)
    applied = frozen.cli("apply", run_id)
    assert applied.exit_code == 0, applied.output
    assert (frozen.repo / "calc.py").read_text() == FIXED
    after = frozen.store.load(run_id).manifest
    assert after["state"] == "applied"
    assert _changed(before, after) == {"state", "updated_at"}
    receipts = list((frozen.store.root / run_id / "applications").glob("*.json"))
    assert len(receipts) == 1
    receipt = json.loads(receipts[0].read_text())
    assert (receipt["run_id"], receipt["apply_id"], receipt["patch_sha256"]) == (
        run_id, after["apply_id"], before["patch_sha256"]
    )


@pytest.mark.parametrize(
    "scenario",
    ["failed", "no_changes", "discarded", "superseded", "running",
     "recovery_required", "applied"],
)
def test_a_released_run_that_is_not_pending_is_refused_by_apply(frozen, scenario):
    frozen.install(scenario)
    run_id = frozen.run_id(scenario)
    before = frozen.stored(scenario)
    refused = frozen.cli("apply", run_id)
    assert refused.exit_code == 1
    assert refused.output.splitlines()[-1] == (
        f"Error: run {run_id} is {STATES[scenario]!r}, not pending"
    )
    assert frozen.stored(scenario) == before
    assert (frozen.repo / "calc.py").read_text() == frozen.bindings["tree"]["calc.py"]


# ── recover: each verdict depends on reading the stored v1 fingerprint ─────


@pytest.mark.parametrize(
    ("scenario", "patch_in_source", "outcome", "state"),
    [
        # Died after the receipt, patch in the source: finish the apply.
        ("applying_receipted", True, "completed", "applied"),
        # Died after recording applying, source untouched: back to pending.
        ("applying_unreceipted", False, "not_applied", "pending"),
        # A bound receipt but the source still matches: undecidable.
        ("applying_receipted", False, "manual_recovery", "recovery_required"),
    ],
)
def test_recover_classifies_a_released_interrupted_apply(
    frozen, scenario, patch_in_source, outcome, state
):
    frozen.install(scenario)
    run_id = frozen.run_id(scenario)
    if patch_in_source:
        patch = frozen.frozen_bytes(scenario, "winner.patch")
        subprocess.run(["git", "apply", "-"], cwd=frozen.repo, input=patch, check=True)
    before = frozen.stored(scenario)
    [report] = frozen.store.reconcile_interrupted_applies(run_id=run_id)
    assert (report.run_id, report.outcome) == (run_id, outcome)
    after = frozen.store.load(run_id).manifest
    assert after["state"] == state
    expected_changes = {
        "completed": {"state", "updated_at"},
        "not_applied": {"state", "updated_at", "apply_id", "apply_owner", "apply_started_at"},
        "manual_recovery": {"state", "updated_at"},
    }[outcome]
    assert _changed(before, after) == expected_changes
    if outcome == "completed":
        [receipt] = (frozen.store.root / run_id / "applications").glob("*.json")
        assert report.receipt == str(receipt)


def test_the_recover_command_finishes_a_released_interrupted_apply(frozen):
    frozen.install("applying_receipted")
    run_id = frozen.run_id("applying_receipted")
    patch = frozen.frozen_bytes("applying_receipted", "winner.patch")
    subprocess.run(["git", "apply", "-"], cwd=frozen.repo, input=patch, check=True)
    [receipt] = (frozen.store.root / run_id / "applications").glob("*.json")
    recovered = frozen.cli("recover", run_id)
    assert recovered.exit_code == 0, recovered.output
    assert recovered.output.splitlines() == [
        f"Run {run_id}: completed — interrupted apply finished (receipt {receipt})"
    ]


