@pytest.fixture
def fake_codex(tmp_path, monkeypatch) -> Path:
    """A `codex` on PATH that records its argv and changes nothing."""
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    log = tmp_path / "codex-argv.jsonl"
    codex = bin_dir / "codex"
    codex.write_text(
        "#!/usr/bin/env python3\n"
        "import json, sys\n"
        f"open({str(log)!r}, 'a').write(json.dumps(sys.argv[1:]) + '\\n')\n"
        "print(json.dumps({'type': 'thread.started', 'thread_id': 'fake-codex-thread'}))\n"
        "print(json.dumps({'type': 'item.completed',"
        " 'item': {'type': 'agent_message', 'text': 'done'}}))\n"
    )
    codex.chmod(codex.stat().st_mode | stat.S_IXUSR)
    monkeypatch.setenv("PATH", f"{bin_dir}{os.pathsep}{os.environ['PATH']}")
    monkeypatch.setenv("SYNCMILL_AGENT_PRIORITY", '["codex"]')
    # The continuation runs the real Supervisor; memory is not what is frozen
    # here, so it never reaches a real backend.
    monkeypatch.setattr("syncmill.supervisor.SyncmillMemory", lambda _cfg: FakeMemory())
    return log


def test_continue_resumes_a_released_pending_run_with_its_patch(frozen, fake_codex):
    frozen.install("pending")
    run_id = frozen.run_id("pending")
    before = frozen.stored("pending")
    continued = frozen.cli("continue", run_id, "and test it")
    assert continued.exit_code == 0, continued.output
    [argv] = [json.loads(line) for line in fake_codex.read_text().splitlines()]
    assert argv[:2] == ["exec", "resume"]
    # A parent without a routing block resumes with no model flag: only the
    # sandbox `-c` overrides come before the session id.
    rest = argv[2:]
    while rest and rest[0] == "-c":
        rest = rest[2:]
    assert rest[0] == "fake-codex-thread"
    assert "-m" not in argv
    child_id = next(
        line.split(": ", 1)[1] for line in continued.output.splitlines()
        if line.startswith("[syncmill] run:")
    )
    child = frozen.store.load(child_id).manifest
    assert child["parent_run_id"] == run_id
    assert "model_routing" not in child["plan"]
    # The child started from the release's patch and added nothing.
    assert frozen.store.patch(child_id) == frozen.frozen_bytes("pending", "winner.patch")
    after = frozen.store.load(run_id).manifest
    assert (after["state"], after["superseded_by"]) == ("superseded", child_id)
    assert _changed(before, after) == {"state", "updated_at"}


@pytest.mark.parametrize(
    ("scenario", "reason"),
    [
        ("closed", "conversation is closed"),
        ("failed", "run has no resumable provider session"),
        ("running", "run has no resumable provider session"),
        ("recovery_required", "run has no resumable provider session"),
        ("discarded", "cannot continue a run in state 'discarded'"),
        ("superseded", "cannot continue a run in state 'superseded'"),
        ("applying_receipted", "cannot continue a run in state 'applying'"),
    ],
)
def test_continue_refuses_a_released_run_it_cannot_resume(
    frozen, fake_codex, scenario, reason
):
    frozen.install(scenario)
    run_id = frozen.run_id(scenario)
    before = frozen.stored(scenario)
    refused = frozen.cli("continue", run_id, "more")
    assert refused.exit_code == 1
    assert refused.output.splitlines()[-1] == f"Error: {reason}"
    assert not fake_codex.exists()
    assert frozen.stored(scenario) == before


