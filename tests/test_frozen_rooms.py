# What each scenario's comparison must say. ``selection`` is None when nothing
# was selected; a v0.1.2 selection was never recorded.
OUTCOMES = {
    "draft": "not_selected",
    "awaiting": "not_selected",
    "ungated": "not_selected",
    "rejected": "not_selected",
    "selected": "selected_not_applied",
    "closed": "not_selected",
    "stale": "not_selected",
    "running": "not_selected",
    "applied": "applied_unreviewed",
    "applying": "unknown",
    "recovered": "unknown",
}
#: (member, eligible, state, gate verdict, why not eligible) per round, as
#: the release recorded them
_PASSED = [("codex", True, "completed", "passed", None),
           ("kimi-code", True, "completed", "passed", None)]
CANDIDATE_ROWS = {
    "ungated": [[("codex", True, "completed", "no_report", None),
                 ("kimi-code", False, "completed", "no_report", "no patch captured")]],
    "rejected": [[("codex", False, "completed", "failed", "quality gate failed"),
                  ("kimi-code", False, "failed", "not_run", "agent did not complete")]],
    "running": [[]],
}
#: (requested lineage, tree) per round, for releases that record provenance
LINEAGE = {
    "awaiting": [("continue-own", "snapshot"), ("continue-own", "continued"),
                 ("branch-from", "branch")],
}


@pytest.mark.parametrize("scenario", list(SCENARIOS))
def test_compare_interprets_a_released_room(release, scenario, tmp_path, monkeypatch):
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    compared = frozen.compare()
    room = compared["room"]
    state, rounds = SCENARIOS[scenario]
    assert (room["room_id"], room["state"], room["round_count"]) == (
        frozen.room_id, state, rounds
    )
    assert room["outcome"]["status"] == OUTCOMES[scenario]
    selected = scenario in ("selected", "applied", "applying", "recovered")
    if not selected:
        assert room["selection"] is None
    elif release == "v0.1.2":
        assert room["selection"]["status"] == "not_recorded"
    else:
        assert room["selection"]["status"] == "bound"
        assert room["selection"]["candidate_id"] == room["selected_candidate_id"]
    # The source was rebound to this repository: it is current, except for a
    # draft, which never recorded one.
    assert compared["source"]["status"] == ("not_recorded" if scenario == "draft" else "current")

    provenance = release != "v0.1.2"
    gated = scenario != "ungated"
    records = {
        row["number"]: {
            "provenance": json.loads(row["provenance_json"]),
            "conversation": json.loads(row["conversation_json"]),
        }
        for row in frozen.rows("SELECT * FROM rounds")
        if provenance and row["provenance_json"] is not None
    }
    groups = compared["rounds"]
    assert [g["number"] for g in groups] == list(range(1, rounds + 1))
    expected_rows = CANDIDATE_ROWS.get(scenario, [_PASSED] * rounds)
    for index, group in enumerate(groups):
        assert [
            (c["member_id"], c["eligible"], c["state"], c["gate"]["verdict"],
             c["not_eligible_reason"])
            for c in group["candidates"]
        ] == expected_rows[index]
        assert all(c["readable"] for c in group["candidates"])
        lineage, gate = group["lineage"], group["gate_settings"]
        conversation = group["conversation"]
        if not provenance:
            assert (lineage["status"], gate["status"]) == ("not_recorded", "not_recorded")
            assert conversation["status"] == "not_recorded"
            continue
        requested, tree = LINEAGE.get(scenario, [("continue-own", "snapshot")])[index]
        assert (lineage["status"], lineage["requested"], lineage["tree"]) == (
            "recorded", requested, tree
        )
        assert (gate["status"], gate["kind"]) == ("recorded", "commands" if gated else "none")
        if gated:
            # v0.2.0 wrote provenance v1, which has no env allowlist; v0.3.0
            # wrote v2, which does.
            assert gate["env_allowlist_status"] == (
                "recorded" if release == "v0.3.0" else "not_recorded"
            )
        assert conversation["status"] == "recorded"
        # Every value the release recorded reaches the comparison as written.
        record = records[group["number"]]
        provenance_gate, tree = record["provenance"]["gate"], record["provenance"]["tree"]
        assert gate["commands"] == provenance_gate.get("commands", [])
        assert gate["timeout_seconds"] == provenance_gate.get("timeout_seconds")
        if gated:
            assert (gate["commands"], gate["timeout_seconds"]) == ([GATE_COMMAND], 300)
        if release == "v0.3.0" and gated:
            assert gate["env_allowlist"] == provenance_gate["env_allowlist"]
            assert gate["env_allowlist"] == (["FAKE_PLAN"] if scenario == "selected" else None)
        if tree["kind"] == "branch":
            assert (
                lineage["base_candidate_id"], lineage["base_round_number"],
                lineage["base_patch_sha256"],
            ) == (tree["base_candidate_id"], tree["base_round_number"], tree["base_patch_sha256"])
            base = [c for c in frozen.candidates() if c["id"] == tree["base_candidate_id"]]
            assert [(c["number"], c["member_id"]) for c in base] == [(2, "codex")]
        if tree["kind"] == "continued":
            assert lineage["members"] == tree["members"]
            assert {m: p["parent_round_number"] for m, p in tree["members"].items()} == {
                "codex": group["number"] - 1, "kimi-code": group["number"] - 1
            }
        members = record["conversation"]["members"]
        for candidate in group["candidates"]:
            shown = candidate["conversation"]
            stored = members[candidate["member_id"]]
            assert {key: shown[key] for key in stored} == stored
            # Round 1 starts cold with the full task; later rounds resume with
            # a delta of the other member's previous candidate.
            first = group["number"] == 1
            assert (stored["session"], stored["context"], stored["since_round"]) == (
                ("cold", "full", None) if first else ("resume", "delta", group["number"] - 1)
            )
            if not first:
                peers = [
                    c["id"] for c in frozen.candidates()
                    if c["number"] == group["number"] - 1
                    and c["member_id"] != candidate["member_id"]
                ]
                assert stored["candidates"] == peers


def test_export_json_is_the_comparison_and_markdown_renders(release, tmp_path, monkeypatch):
    frozen = Frozen(release, "awaiting", tmp_path, monkeypatch)
    exported = frozen.cli("room", "export", frozen.room_id, "--all-rounds", "--format", "json")
    assert exported.exit_code == 0, exported.output
    assert json.loads(exported.output) == frozen.compare()
    markdown = frozen.cli("room", "export", frozen.room_id, "--all-rounds")
    assert markdown.exit_code == 0, markdown.output
    for candidate in frozen.candidates():
        assert candidate["id"] in markdown.output
    if release != "v0.1.2":
        # The recorded gate command and branch base reach the markdown too.
        assert GATE_COMMAND in markdown.output
        [round3] = frozen.rows("SELECT provenance_json FROM rounds WHERE number = 3")
        base = json.loads(round3["provenance_json"])["tree"]["base_candidate_id"]
        assert f"snapshot plus candidate {base}'s patch" in markdown.output


