@pytest.mark.parametrize("scenario", list(SCENARIOS))
def test_list_rounds_and_show_read_a_released_room(release, scenario, tmp_path, monkeypatch):
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    state, rounds = SCENARIOS[scenario]
    listed = frozen.cli("room", "list")
    assert listed.exit_code == 0, listed.output
    [row] = listed.output.splitlines()
    assert row.split()[:4] == [frozen.room_id, state, f"rounds:{rounds}", "members:2"]

    shown_rounds = frozen.cli("room", "rounds", frozen.room_id)
    assert shown_rounds.exit_code == 0, shown_rounds.output
    stored_rounds = frozen.rows("SELECT number, state FROM rounds ORDER BY number")
    assert [line.split()[:2] for line in shown_rounds.output.splitlines()] == [
        [str(r["number"]), r["state"]] for r in stored_rounds
    ]
    assert len(stored_rounds) == rounds

    shown = frozen.cli("room", "show", frozen.room_id)
    assert shown.exit_code == 0, shown.output
    room = json.loads(shown.output)
    [stored] = frozen.rows("SELECT * FROM rooms")
    assert (room["id"], room["state"], room["revision"], room["repo_root"]) == (
        stored["id"], state, stored["revision"], str(frozen.repo)
    )
    assert sorted(c["id"] for c in room["candidates"]) == sorted(
        c["id"] for c in frozen.candidates()
    )
    events = frozen.rows("SELECT kind FROM room_events ORDER BY sequence")
    assert [e["kind"] for e in room["events"]] == [e["kind"] for e in events]


