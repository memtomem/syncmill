FROZEN = Path(__file__).parent / "fixtures" / "persisted" / "rooms"
RELEASES = sorted(p.name for p in FROZEN.iterdir() if p.is_dir())

#: scenario -> (room state, rounds) as the release left it
SCENARIOS = {
    "draft": ("draft", 0),
    "awaiting": ("awaiting_decision", 3),
    "ungated": ("awaiting_decision", 1),
    "rejected": ("awaiting_decision", 1),
    "selected": ("selected", 1),
    "closed": ("closed", 1),
    "stale": ("stale", 1),
    "running": ("running", 1),
    "applied": ("applied", 1),
    "applying": ("applying", 1),
    "recovered": ("recovery_required", 1),
}

#: Machine-bound columns. ``path``: under the generating machine's directory;
#: ``fingerprint``: the source fingerprint; ``owner``: "<pid>-<token>".
BOUND = {
    ("rooms", "repo_root"): "path",
    ("rooms", "recovery_path"): "path",
    ("rooms", "source_fingerprint"): "fingerprint",
    ("rooms", "apply_owner"): "owner",
    ("rooms", "close_owner"): "owner",
    ("rooms", "workspace_owner"): "owner",
    ("rounds", "lease_owner"): "owner",
    ("candidates", "artifact_path"): "path",
    ("candidates", "source_fingerprint"): "fingerprint",
    ("room_workspaces", "path"): "path",
    ("room_workspaces", "control_repo"): "path",
    ("room_workspaces", "run_root"): "path",
}
#: Above any pid the platform hands out; ``_worker_alive`` reports it dead
#: without probing.
DEAD_PID = str(0x1_0000_0000)
#: The gate every gated scenario ran (freeze.py's GATE).
GATE_COMMAND = 'python -c "from calc import add; assert add(2, 3) == 5"'
FIXED = {
    "codex": "def add(a, b):\n    return a + b\n",
    "kimi-code": "def add(a, b):\n    return b + a\n",
}


def _bindings(release: str) -> dict:
    return json.loads((FROZEN / release / "bindings.json").read_text())


def _cells(conn: sqlite3.Connection) -> dict[tuple[str, str], list]:
    tables = [r[0] for r in conn.execute(
        "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'"
    )]
    cells: dict[tuple[str, str], list] = {}
    for table in tables:
        columns = [r[1] for r in conn.execute(f"PRAGMA table_info({table})")]
        rows = conn.execute(f"SELECT * FROM {table} ORDER BY rowid").fetchall()
        for index, column in enumerate(columns):
            cells[(table, column)] = [row[index] for row in rows]
    return cells


class Frozen:
    """One release scenario installed as a project bound to ``repo``."""

    def __init__(self, release: str, scenario: str, tmp_path: Path, monkeypatch):
        self.release = release
        self.scenario = scenario
        self.bindings = _bindings(release)
        self.facts = self.bindings["scenarios"][scenario]
        self.dir = FROZEN / release / scenario
        self.root = tmp_path.resolve()
        self.repo = self.root / "repo"
        self.repo.mkdir()
        for name, text in self.bindings["tree"].items():
            (self.repo / name).write_text(text, encoding="utf-8")
        for argv in (
            ["init", "-q"],
            ["add", "-A"],
            ["-c", "user.name=t", "-c", "user.email=t@t.test", "-c",
             "commit.gpgsign=false", "commit", "-q", "-m", "frozen tree"],
        ):
            subprocess.run(["git", *argv], cwd=self.repo, check=True, capture_output=True)
        self.runs_root = self.root / "state" / "runs"
        self.project_dir = self.runs_root / self.facts["project_id"]
        self.room_id = self.facts["room_id"]
        monkeypatch.setenv("SYNCMILL_ROOMS__ENABLED", "true")
        monkeypatch.setenv("SYNCMILL_RUNS__ROOT", str(self.runs_root))
        monkeypatch.setenv("SYNCMILL_WORKSPACE__ROOT", str(self.root / "state" / "workspaces"))
        monkeypatch.setenv("SYNCMILL_PROJECT__ID", self.facts["project_id"])
        self.fingerprints = {
            stored: repository_fingerprint(self.repo, like=stored)
            for stored in self.facts["source_fingerprints"]
        }
        self._install()

    # ── installation and rebinding ──────────────────────────────────────

    def _rebind_path(self, value: str) -> str:
        old = self.bindings["box_root"]
        assert value == old or value.startswith(old + "/"), value
        return str(self.root) + value[len(old):]

    def _rebind(self, kind: str, value):
        if value is None:
            return None
        if kind == "path":
            return self._rebind_path(value)
        if kind == "fingerprint":
            return self.fingerprints[value]
        assert re.fullmatch(r"\d+-[0-9a-f]+", value), value
        return DEAD_PID + "-" + value.split("-", 1)[1]

    def _install(self) -> None:
        shutil.copytree(self.dir, self.project_dir)
        db = self.project_dir / "rooms" / "rooms.sqlite3"
        conn = sqlite3.connect(db)  # replays a crash's WAL, as any open would
        try:
            before = _cells(conn)
            self.rebound: dict[tuple[str, str], int] = {}
            for (table, column), kind in BOUND.items():
                if (table, column) not in before:
                    continue
                rows = conn.execute(f"SELECT rowid, {column} FROM {table}").fetchall()
                for rowid, value in rows:
                    new = self._rebind(kind, value)
                    if new != value:
                        conn.execute(
                            f"UPDATE {table} SET {column} = ? WHERE rowid = ?", (new, rowid)
                        )
                        self.rebound[(table, column)] = self.rebound.get((table, column), 0) + 1
            conn.commit()
            after = _cells(conn)
        finally:
            conn.close()
        assert after.keys() == before.keys()
        for key in before:
            if key not in BOUND:
                assert after[key] == before[key], key
        # Candidate manifests carry the fingerprint; run artifacts carry the
        # repo root and fingerprint, receipts the repo root. Exact counts.
        for manifest in (self.project_dir / "rooms" / "artifacts").glob("*/candidates/*/manifest.json"):
            self._replace_bytes(manifest, fingerprints=1, paths=0)
        for manifest in self.project_dir.glob("runs/*/manifest.json"):
            self._replace_bytes(manifest, fingerprints=1, paths=1)
        for receipt in self.project_dir.glob("runs/*/applications/*.json"):
            self._replace_bytes(receipt, fingerprints=0, paths=1)

    def _replace_bytes(self, path: Path, *, fingerprints: int, paths: int) -> None:
        data = path.read_bytes()
        found = 0
        for stored, live in self.fingerprints.items():
            found += data.count(stored.encode())
            data = data.replace(stored.encode(), live.encode())
        assert found == fingerprints, path
        old = self.bindings["box_root"].encode()
        assert data.count(old) == paths, path
        data = data.replace(old, str(self.root).encode())
        path.write_bytes(data)

    # ── reading ─────────────────────────────────────────────────────────

    def db(self) -> sqlite3.Connection:
        conn = sqlite3.connect(self.project_dir / "rooms" / "rooms.sqlite3")
        conn.row_factory = sqlite3.Row
        return conn

    def rows(self, sql: str, *params) -> list[dict]:
        conn = self.db()
        try:
            return [dict(row) for row in conn.execute(sql, params)]
        finally:
            conn.close()

    def candidates(self) -> list[dict]:
        return self.rows(
            "SELECT c.*, r.number FROM candidates c JOIN rounds r ON r.id = c.round_id "
            "ORDER BY r.number, c.member_id"
        )

    def frozen_bytes(self, candidate_id: str, name: str) -> bytes:
        return (
            self.dir / "rooms" / "artifacts" / self.room_id / "candidates" / candidate_id / name
        ).read_bytes()

    def cli(self, *argv: str):
        return CliRunner().invoke(cli, [*argv, "--repo", str(self.repo)])

    def compare(self) -> dict:
        shown = self.cli("room", "compare", self.room_id, "--all-rounds", "--json")
        assert shown.exit_code == 0, shown.output
        return json.loads(shown.output)


def frozen(release: str, scenario: str, tmp_path: Path, monkeypatch) -> Frozen:
    return Frozen(release, scenario, tmp_path, monkeypatch)


