"""Released rooms, read by the current readers (#271, persisted contracts D).

The stores under ``fixtures/persisted/rooms/<release>/<scenario>/`` were written
by that release's own ``syncmill room`` commands (see ``freeze.py`` there) and
are never regenerated by the current writer. Each scenario is one project:
its room database (with the WAL a killed process leaves), candidate artifacts,
member logs and any room-bound run artifact. Room workspaces were not frozen;
readers that need a live workspace are not covered here.

Only machine-bound cells are rebound, each in a named column: paths under the
generating machine's directory, the source fingerprint (recomputed in the
stored value's own version) and owner pids (set to a pid that cannot be
alive). ``_install`` asserts that every other cell is unchanged.
"""

