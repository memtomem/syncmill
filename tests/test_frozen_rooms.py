SESSIONS = {"codex": "fake-codex-thread", "kimi-code": "fake-kimi-session"}


def _member_sessions(frozen: Frozen) -> dict[str, str]:
    """The sessions the next round would resume, as production reads them."""
    from syncmill.cli import _room_coordinator

    _, _, coordinator = _room_coordinator(frozen.repo)
    try:
        return coordinator.store.member_sessions(frozen.room_id)
    finally:
        coordinator.close()


def test_a_released_room_keeps_its_sessions_when_its_workspaces_go(
    release, tmp_path, monkeypatch
):
    # v0.1.2 kept provider sessions only on its workspace rows; v0.2.0 also
    # wrote rooms.sessions_json. Opening the store backfills the durable copy,
    # so the sessions survive the workspace rows being removed.
    frozen = Frozen(release, "awaiting", tmp_path, monkeypatch)
    assert _has(frozen, "rooms", "sessions_json") == (release != "v0.1.2")
    stored = frozen.rows(
        "SELECT member_id, provider_session_id FROM room_workspaces ORDER BY member_id"
    )
    assert {r["member_id"]: r["provider_session_id"] for r in stored} == SESSIONS
    assert _member_sessions(frozen) == SESSIONS
    conn = frozen.db()
    try:
        conn.execute("DELETE FROM room_workspaces")
        conn.commit()
    finally:
        conn.close()
    assert _member_sessions(frozen) == SESSIONS


@pytest.mark.parametrize("scenario", ["closed", "applied"])
def test_sessions_of_a_released_room_without_workspaces(
    release, scenario, tmp_path, monkeypatch
):
    # Closing or applying removed the workspace rows. From v0.2.0 the durable
    # sessions_json is all that is left; v0.1.2 had none, so nothing is.
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    assert frozen.rows("SELECT * FROM room_workspaces") == []
    assert _member_sessions(frozen) == ({} if release == "v0.1.2" else SESSIONS)
