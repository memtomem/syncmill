def _room(frozen: Frozen) -> dict:
    [room] = frozen.rows("SELECT * FROM rooms")
    return room


@pytest.mark.parametrize("scenario", ["awaiting", "ungated"])
def test_select_then_apply_a_released_room(release, scenario, tmp_path, monkeypatch):
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    candidate = [c for c in frozen.candidates() if c["eligible"]][-1]
    selected = frozen.cli("room", "select", frozen.room_id, candidate["id"])
    assert selected.exit_code == 0, selected.output
    room = _room(frozen)
    assert (room["state"], room["selected_candidate_id"]) == ("selected", candidate["id"])
    record = json.loads(room["selection_json"])
    assert (record["schema_version"], record["candidate_id"]) == (1, candidate["id"])
    assert record["patch_sha256"] == hashlib.sha256(
        frozen.frozen_bytes(candidate["id"], "candidate.patch")
    ).hexdigest()

    applied = frozen.cli("room", "apply", frozen.room_id)
    assert applied.exit_code == 0, applied.output
    room = _room(frozen)
    assert room["state"] == "applied"
    assert (frozen.repo / "calc.py").read_text() == FIXED[candidate["member_id"]]
    # What the released candidate's own gate record supports, read on real old bytes.
    lines = applied.output.splitlines()
    assert ("[syncmill] Unverified: this candidate has no quality gate report, "
            "and --verify was not used." in lines) == (scenario == "ungated")
    assert not [line for line in lines if line.startswith("[syncmill] Verification not recorded")]


def test_a_released_selection_applies(release, tmp_path, monkeypatch):
    # v0.1.2 recorded no selection document; its absence is not a mismatch.
    frozen = Frozen(release, "selected", tmp_path, monkeypatch)
    before = _room(frozen)
    applied = frozen.cli("room", "apply", frozen.room_id)
    assert applied.exit_code == 0, applied.output
    room = _room(frozen)
    assert room["state"] == "applied"
    assert room["selected_candidate_id"] == before["selected_candidate_id"]
    [candidate] = [c for c in frozen.candidates() if c["id"] == before["selected_candidate_id"]]
    assert (frozen.repo / "calc.py").read_text() == FIXED[candidate["member_id"]]
    manifest = json.loads(
        (frozen.project_dir / "runs" / room["applied_run_id"] / "manifest.json").read_text()
    )
    assert (manifest["state"], manifest["strategy"], manifest["plan"]["origin"]) == (
        "applied", "room", "room"
    )
    assert manifest["plan"]["candidate_id"] == candidate["id"]


