def test_room_recover_finishes_a_released_interrupted_apply(release, tmp_path, monkeypatch):
    # The release died at the artifact's applied flip with the patch in the
    # source; the room is applying and its owner is gone.
    frozen = Frozen(release, "applying", tmp_path, monkeypatch)
    run_id = _room(frozen)["apply_run_id"]
    run_dir = frozen.project_dir / "runs" / run_id
    subprocess.run(
        ["git", "apply", "-"], cwd=frozen.repo,
        input=(run_dir / "winner.patch").read_bytes(), check=True,
    )
    recovered = frozen.cli("room", "recover")
    assert recovered.exit_code == 0, recovered.output
    assert recovered.output.splitlines() == [
        f"Recovered room {frozen.room_id}; inspect or close it explicitly"
    ]
    room = _room(frozen)
    assert (room["state"], room["apply_run_id"], room["apply_owner"]) == (
        "recovery_required", run_id, None
    )
    [event] = frozen.rows(
        "SELECT kind, payload_json FROM room_events ORDER BY sequence DESC LIMIT 1"
    )
    assert event["kind"] == "apply.interrupted_recovered"
    assert json.loads(event["payload_json"]) == {
        "run_id": run_id,
        "artifact_state": "recovery_required",
        "artifact_binding": "valid",
        "source_matches": False,
    }
    assert json.loads((run_dir / "manifest.json").read_text())["state"] == "recovery_required"


