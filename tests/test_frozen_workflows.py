@pytest.mark.parametrize("scenario", list(SCENARIOS) + list(SCENARIOS_V030))
def test_install_rebinds_only_machine_bound_values(release, scenario, tmp_path, monkeypatch):
    if scenario not in scenarios(release):
        pytest.skip(f"{release} has no {scenario}")
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    for row in frozen.rows("SELECT * FROM workflows"):
        assert row["repo_root"] == str(frozen.repo)
        assert fingerprint_version(row["source_fingerprint"]) == 1
        assert row["source_fingerprint"] == repository_fingerprint(
            frozen.repo, like=row["source_fingerprint"]
        )
        if row["lease_owner"] is not None:
            assert row["lease_owner"] == f"{DEAD_PID}@{socket.gethostname()}"
    assert re.fullmatch(r"wf-[0-9a-f]{16}", frozen.workflow_id)


def _immutable_rows(release: str, scenario: str) -> list[dict]:
    """The rows exactly as the release left them (no open, no WAL replay)."""
    db = FROZEN / release / scenario / "workflows" / "workflows.db"
    conn = sqlite3.connect(f"file:{db}?mode=ro&immutable=1", uri=True)
    conn.row_factory = sqlite3.Row
    try:
        return [dict(row) for row in conn.execute(
            "SELECT * FROM workflows ORDER BY created_at, workflow_id"
        )]
    finally:
        conn.close()


def _lines(text: str, prefix: str) -> list[str]:
    return [line for line in text.splitlines() if line.startswith(prefix)]


def _clock(monkeypatch, at) -> None:
    """Fix the workflow module's clock, so a lease decision cannot depend on
    how old the fixture is: the released heartbeat ages in real time."""
    from datetime import datetime

    class Fixed(datetime):
        @classmethod
        def now(cls, tz=None):
            return at if tz is None else at.astimezone(tz)

    monkeypatch.setattr("syncmill.workflow.datetime", Fixed)


def _fresh_heartbeat(frozen: "Frozen"):
    """One second after the released heartbeat: only the owner's pid can
    make the lease stale."""
    from datetime import datetime, timedelta

    return datetime.fromisoformat(frozen.row()["lease_heartbeat"]) + timedelta(seconds=1)


