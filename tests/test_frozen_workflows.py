@pytest.mark.parametrize("scenario", list(SCENARIOS) + list(SCENARIOS_V030))
def test_list_and_show_read_a_released_workflow(release, scenario, tmp_path, monkeypatch):
    if scenario not in scenarios(release):
        pytest.skip(f"{release} has no {scenario}")
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    released = _immutable_rows(release, scenario)
    manifests = {r["workflow_id"]: json.loads(r["manifest_json"]) for r in released}

    # The release's own state, before any HEAD reader can recover it.
    listed = frozen.cli("workflow", "list")
    assert listed.exit_code == 0, listed.output
    shown_rows = [line.split()[:2] for line in listed.output.splitlines()
                  if line.startswith("wf-")]
    assert sorted(shown_rows) == sorted(
        [r["workflow_id"], r["state"]] for r in released
    )
    for row in released:
        manifest = manifests[row["workflow_id"]]
        assert [manifest["nodes"][n]["state"] for n in ("draft", "fix")] == list(NODES[scenario])

    shown = frozen.cli("workflow", "show", frozen.workflow_id)
    assert shown.exit_code == 0, shown.output
    text = shown.output
    row = released[-1]
    manifest = manifests[row["workflow_id"]]
    expected_state = "recovery_required" if scenario in DEAD_OWNER else row["state"]
    origin = {"created": "file", "revised": "revision"}.get(scenario, "planner")
    assert _lines(text, "workflow: ") == [f"workflow: {frozen.workflow_id}"]
    assert _lines(text, "state: ") == [f"state: {expected_state}"]
    assert _lines(text, "calls_used: ") == [f"calls_used: {manifest['calls_used']}"]
    usage = manifest["usage"]
    assert _lines(text, "usage: ") == [
        f"usage: input={usage['input_tokens']} output={usage['output_tokens']} "
        f"cost_usd={usage['total_cost_usd']:.6f}"
    ]
    loaded = _store(frozen).load(frozen.workflow_id)
    assert (loaded.input_tokens, loaded.output_tokens, loaded.total_cost_usd) == (
        usage["input_tokens"], usage["output_tokens"], usage["total_cost_usd"]
    )
    if scenario not in ("created", "revised"):
        # The planner (and any node that ran) reported tokens: zero would
        # not tell a dropped value from a recorded one.
        assert usage["input_tokens"] > 0
    assert _lines(text, "plan_origin: ") == [f"plan_origin: {origin}"]
    assert _lines(text, "goal: ") == [f"goal: {json.loads(row['spec_json'])['goal']}"]
    final = row["final_run_id"]
    assert _lines(text, "final_run: ") == ([f"final_run: {final}"] if final else [])
    states = dict(zip(("draft", "fix"), NODES[scenario]))
    if scenario in DEAD_OWNER:
        # The owner is gone: the node it was running is interrupted.
        states = {n: ("interrupted" if s == "running" else s) for n, s in states.items()}
    assert _lines(text, "  draft: ") == [
        f"  draft: {states['draft']} agent=codex "
        f"attempts={manifest['nodes']['draft']['attempts']}/1 needs=-"
    ]
    assert _lines(text, "  fix: ") == [
        f"  fix: {states['fix']} agent=kimi-code "
        f"attempts={manifest['nodes']['fix']['attempts']}/1 needs=draft (final)"
    ]


@pytest.mark.parametrize("scenario", sorted(DEAD_OWNER))
@pytest.mark.parametrize("command", ["show", "status"])
def test_show_and_status_recover_a_released_dead_owner(
    release, scenario, command, tmp_path, monkeypatch
):
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    _clock(monkeypatch, _fresh_heartbeat(frozen))
    before = frozen.row()
    assert before["state"] == "running"
    assert before["lease_owner"] == f"{DEAD_PID}@{socket.gethostname()}"
    result = frozen.cli("workflow", command, frozen.workflow_id)
    assert result.exit_code == 0, result.output
    after = frozen.row()
    assert (after["state"], after["lease_owner"], after["lease_id"]) == (
        "recovery_required", None, None
    )
    manifest = json.loads(after["manifest_json"])
    assert manifest["error"] == "execution owner lost; resume explicitly"
    # The node the dead owner was running is interrupted; its finished
    # dependency keeps its bundle.
    released = json.loads(before["manifest_json"])["nodes"]
    assert manifest["nodes"]["draft"] == released["draft"]
    expected_fix = "interrupted" if released["fix"]["state"] == "running" else released["fix"]["state"]
    assert manifest["nodes"]["fix"]["state"] == expected_fix


@pytest.mark.parametrize("command", ["show", "status"])
def test_a_released_lease_whose_owner_lives_is_never_taken(release, command, tmp_path, monkeypatch):
    # The released owner is read as pid@host: on this host the pid's answer
    # is final, so a live owner keeps the lease although the released
    # heartbeat is long past the lease timeout.
    import os

    frozen = Frozen(release, "running", tmp_path, monkeypatch)
    conn = sqlite3.connect(frozen.project_dir / "workflows" / "workflows.db")
    try:
        conn.execute("UPDATE workflows SET lease_owner = ?",
                     (f"{os.getpid()}@{socket.gethostname()}",))
        conn.commit()
    finally:
        conn.close()
    # Long past any lease timeout: only the pid's answer keeps the lease.
    from datetime import UTC, datetime

    _clock(monkeypatch, datetime(2100, 1, 1, tzinfo=UTC))
    lease = ("state", "lease_owner", "lease_id", "lease_heartbeat", "manifest_json", "revision")
    before = {key: frozen.row()[key] for key in lease}
    result = frozen.cli("workflow", command, frozen.workflow_id)
    assert result.exit_code == 0, result.output
    # (Opening a v0.2.0 store adds v0.3.0's columns; the lease is untouched.)
    assert {key: frozen.row()[key] for key in lease} == before
    assert before["state"] == "running"


