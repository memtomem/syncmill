"""Released workflows, read by the current readers (#271, persisted contracts D).

The stores under ``fixtures/persisted/workflows/<release>/<scenario>/`` were
written by that release's own ``syncmill workflow`` commands (see ``freeze.py``
there) and are never regenerated by the current writer. Each scenario is one
project: its workflow database, the workflow directories (spec, planner
output, node bundles, stream logs) and any workflow-origin run artifact.
Workspaces and job records were not frozen.

Only machine-bound values are rebound, each in a named place: the repository
root and source fingerprint (recomputed in the stored value's own version) of
every workflow row, a lease owner's ``pid@host`` (set to a pid that cannot be
alive on this host), and the root and fingerprint of a final run artifact.
``spec_json``, node bundles and ``commit.json`` are never touched: digests
cover their bytes. ``_install`` asserts that every other cell is unchanged.

The later sections run HEAD on the released stores: ``run``, ``resume`` and
``revise`` of released rows, the launch's reads before a job starts, and
``apply --verify`` of a released final artifact.
"""

from __future__ import annotations

