@pytest.mark.parametrize("scenario", ["planned", "completed", "created", "revised"])
def test_the_stored_spec_reads_back_with_its_digest(release, scenario, tmp_path, monkeypatch):
    if scenario not in scenarios(release):
        pytest.skip(f"{release} has no {scenario}")
    from syncmill.workflow import WorkflowSpec

    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    for released in _immutable_rows(release, scenario):
        workflow_id = released["workflow_id"]
        manifest = json.loads(released["manifest_json"])
        spec = WorkflowSpec.model_validate_json(released["spec_json"])
        assert spec.digest() == manifest["spec_sha256"]
        # The spec file beside the row holds the same plan.
        on_disk = json.loads(frozen.frozen_bytes(f"workflows/{workflow_id}/spec.json"))
        assert WorkflowSpec.model_validate(on_disk).digest() == manifest["spec_sha256"]

        prompts = frozen.cli("workflow", "show", workflow_id, "--prompts")
        assert prompts.exit_code == 0, prompts.output
        lines = prompts.output.splitlines()
        for node in spec.nodes:
            at = lines.index("    prompt:", lines.index(next(
                line for line in lines if line.startswith(f"  {node.id}: ")
            )))
            assert lines[at + 1] == f"      {node.prompt}"

        exported = frozen.cli("workflow", "export", workflow_id)
        assert exported.exit_code == 0, exported.output
        document = json.loads(exported.stdout)
        assert WorkflowSpec.model_validate(document).digest() == manifest["spec_sha256"]
        assert document["goal"] == spec.goal
        assert [(n["id"], n["agent"], n["prompt"], n["needs"]) for n in document["nodes"]] == [
            (n.id, n.agent, n.prompt, n.needs) for n in spec.nodes
        ]
    # spec_json itself is never rebound or rewritten.
    assert [r["spec_json"] for r in frozen.rows("SELECT spec_json FROM workflows "
                                                 "ORDER BY created_at, workflow_id")] == [
        r["spec_json"] for r in _immutable_rows(release, scenario)
    ]


