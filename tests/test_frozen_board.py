"""Released work-boards, read by the current readers (#271, persisted contracts D).

The databases under ``fixtures/persisted/board/<release>/<scenario>/`` were
written by that release's own ``syncmill board`` commands (see ``freeze.py``
there) and are never regenerated by the current writer. ``bindings.json`` holds,
per scenario, what the RELEASE's own interpreter read from a scratch copy of
each database: every item through ``Board.get``, its transitions, the active
decisions, every decision row through ``_row_to_decision``, and ``stats`` at
fixed clocks. Those reads are the interpretation HEAD must keep; the raw cells
are checked beside them, so a reader and a writer drifting together still fail.

The board stores nothing bound to the generating machine (freeze.py refuses a
cell holding its paths or hostname), so nothing is rebound. Every test works on
a copy; HEAD opening a released database adds columns and tables to it.
"""

