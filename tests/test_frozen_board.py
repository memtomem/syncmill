# ── HEAD's first open of a released database ──────────────────────────────


@pytest.mark.parametrize(("release", "scenario"), CASES)
def test_head_open_adds_its_schema_without_touching_a_released_cell(
    release, scenario, frozen, tmp_path
):
    f = frozen(release, scenario)
    # The baseline comes from a second copy: reading it replays and
    # checkpoints a killed run's WAL, and HEAD must open the original shape.
    pristine = tmp_path / "pristine"
    shutil.copytree(f.source, pristine)
    before = _cells(pristine / "board.db")

    f.board().close()
    after = _cells(f.db)

    for key, values in before.items():
        assert after[key] == values, key
    added = set(after) - set(before)
    tables = {table for table, _ in added}
    assert {k for k in added if k[0] not in ADDED_TABLES[release]} == ADDED_COLUMNS[release]
    assert tables - {t for t, _ in ADDED_COLUMNS[release]} == ADDED_TABLES[release]
    for key in added:
        assert all(v is None for v in after[key]), key  # nullable columns, empty tables
    for name in ("board.db", "board.db-wal", "board.db-shm"):
        path = f.dir / name
        if path.exists():
            assert stat.S_IMODE(os.stat(path).st_mode) == 0o600, name

    # A second open changes nothing: the migration and the ledger backfill
    # leave a migrated release alone (every release claimed and wrote its
    # ledger row in one transaction, so there is nothing to backfill).
    f.board().close()
    assert _cells(f.db) == after


