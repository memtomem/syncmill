@pytest.mark.parametrize("release", RELEASES)
def test_decisions_read_as_the_release_did_and_stay_unbound(release, frozen):
    f = frozen(release, "lifecycle")
    board = f.board()
    try:
        for goal, expected in f.read["active_decisions"].items():
            got = board.active_decisions() if goal == "*" else board.active_decisions(goal=goal)
            assert plain(got) == [_decision(d) for d in expected], goal
        mapped = [plain(_row_to_decision(r))
                  for r in f.rows("SELECT * FROM decisions ORDER BY rowid")]
        assert mapped == [_decision(d) for d in f.read["decisions_mapped"]]
        retired = [d for d in mapped if d["superseded_by"]]
        assert [d["id"] for d in retired] == [f.decisions["superseded"]]
        assert retired[0]["superseded_by"] == f.decisions["replacement"]
        assert retired[0]["superseded_at"] is not None
        # Legacy decisions are unbound: included for any project, never a
        # project's lesson. (A project-bound lesson is excluded elsewhere:
        # test_lessons.py covers the project filter with mixed rows.)
        assert all(lesson_source(d) is None for d in board.active_decisions())
        assert [d.id for d in board.active_decisions(project_id="frozen-board")] == \
            [d["id"] for d in f.read["active_decisions"]["*"]]
        assert board.project_lessons("frozen-board") == []
        assert board.project_lessons("frozen-board", goal="backend") == []
    finally:
        board.close()
    for goal, expected in f.read["active_decisions"].items():
        argv = ["board", "decisions"] + ([] if goal == "*" else ["--goal", goal])
        shown = f.cli(*argv)
