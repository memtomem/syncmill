def _bindings(release: str) -> dict:
    return json.loads((FROZEN / release / "bindings.json").read_text(encoding="utf-8"))


def _cells(db: Path) -> dict[tuple[str, str], list]:
    conn = sqlite3.connect(db)
    try:
        tables = [r[0] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'"
        )]
        cells: dict[tuple[str, str], list] = {}
        for table in tables:
            columns = [r[1] for r in conn.execute(f"PRAGMA table_info({table})")]
            rows = conn.execute(f"SELECT * FROM {table} ORDER BY rowid").fetchall()
            for index, column in enumerate(columns):
                cells[(table, column)] = [row[index] for row in rows]
        return cells
    finally:
        conn.close()


def _schema(db: Path) -> tuple[dict[str, list[str]], list[str]]:
    conn = sqlite3.connect(db)
    try:
        tables = {
            name: [r[1] for r in conn.execute(f"PRAGMA table_info({name})")]
            for (name,) in conn.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table' "
                "AND name NOT LIKE 'sqlite_%' ORDER BY name"
            ).fetchall()
        }
        indexes = sorted(n for (n,) in conn.execute(
            "SELECT name FROM sqlite_master WHERE type = 'index' AND name NOT LIKE 'sqlite_%'"
        ))
        return tables, indexes
    finally:
        conn.close()


def plain(value):
    """A dataclass as the JSON freeze.py stored the release's reads in."""
    if isinstance(value, enum.Enum):
        return value.value
    if dataclasses.is_dataclass(value):
        return {f.name: plain(getattr(value, f.name)) for f in dataclasses.fields(value)}
    if isinstance(value, (list, tuple)):
        return [plain(v) for v in value]
    if isinstance(value, dict):
        return {k: plain(v) for k, v in value.items()}
    return value


def _item(read: dict) -> WorkItem:
    return WorkItem(**{
        **read,
        "state": WorkState(read["state"]),
        "evidence": [Evidence(**e) for e in read["evidence"]],
    })


#: Fields HEAD's Decision has and no release stored: a released decision is
#: unbound and was never promoted.
_UNBOUND = {"project_id": None, "provenance": None}


def _decision(read: dict) -> dict:
    return {**read, **_UNBOUND}


class Frozen:
    """One release scenario copied into ``tmp_path`` with the board enabled on it."""

    def __init__(self, release: str, scenario: str, tmp_path: Path, monkeypatch):
        self.release = release
        self.scenario = scenario
        self.bindings = _bindings(release)
        self.facts = self.bindings["scenarios"][scenario]
        self.read = self.facts["release_read"]
        self.items = self.facts["items"]
        self.decisions = self.facts["decisions"]
        self.frozen_at = self.facts["frozen_at"]
        self.stall = self.bindings["stall_seconds"]
        self.source = FROZEN / release / scenario
        self.dir = tmp_path / "board" / scenario
        shutil.copytree(self.source, self.dir)
        self.db = self.dir / "board.db"
        self._monkeypatch = monkeypatch
        monkeypatch.setenv("SYNCMILL_BOARD__ENABLED", "true")
        monkeypatch.setenv("SYNCMILL_BOARD__DB_PATH", str(self.db))
        monkeypatch.setenv("SYNCMILL_BOARD__STALL_SECONDS", str(self.stall))
        self.clock(self.frozen_at)

    def clock(self, now: float) -> None:
        """Fix the clock of every board the CLI opens, and of the evidence it stamps."""
        def build_board(config):
            return Board(config.db_path, now=lambda: now,
                         lease_timeout_seconds=config.lease_timeout_seconds,
                         stall_seconds=config.stall_seconds)
        self._monkeypatch.setattr(cli_module, "build_board", build_board)
        self._monkeypatch.setattr(cli_module.time, "time", lambda: now)

    def board(self) -> Board:
        return Board(str(self.db), now=lambda: self.frozen_at, stall_seconds=self.stall)

    def cli(self, *argv: str):
        return CliRunner().invoke(cli, list(argv))

    def rows(self, sql: str, *params) -> list[sqlite3.Row]:
        conn = sqlite3.connect(self.db)
        conn.row_factory = sqlite3.Row
        try:
            return conn.execute(sql, params).fetchall()
        finally:
            conn.close()

    def expected_items(self) -> list[WorkItem]:
        return [_item(self.read["items"][i]) for i in self.read["order"]]


@pytest.fixture
def frozen(request, tmp_path, monkeypatch):
    def install(release: str, scenario: str) -> Frozen:
        return Frozen(release, scenario, tmp_path, monkeypatch)
    return install


