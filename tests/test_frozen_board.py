def _evidence_with(row, **change) -> str:
    evidence = json.loads(row["evidence"])
    evidence[0].update(change)
    return json.dumps(evidence)


@pytest.mark.parametrize("release", RELEASES)
@pytest.mark.parametrize("change", [
    pytest.param(lambda row: ("task", row["task"] + " (edited)"), id="task"),
    pytest.param(lambda row: ("inputs", json.dumps(json.loads(row["inputs"])[:4])), id="inputs"),
    pytest.param(lambda row: ("evidence", _evidence_with(row, ref="sha256:" + "0" * 64)),
                 id="evidence-ref"),
    pytest.param(lambda row: ("evidence", _evidence_with(row, by="someone")), id="evidence-by"),
    pytest.param(lambda row: ("evidence", _evidence_with(row, kind="manual")), id="evidence-kind"),
    pytest.param(lambda row: ("evidence", _evidence_with(row, passed=True)), id="evidence-passed"),
])
def test_reimport_refuses_a_released_candidate_whose_provenance_differs(
    release, change, frozen
):
    # The item id is a uuid5 of the provenance, so only a stored row that no
    # longer matches it can collide; each checked component is changed alone.
    f = frozen(release, "lifecycle")
    f.board().close()
    item_id = f.items["imported-1"]
    row = f.rows("SELECT * FROM work_items WHERE id = ?", item_id)[0]
    column, value = change(row)
    conn = sqlite3.connect(f.db)
    with conn:
        conn.execute(f"UPDATE work_items SET {column} = ? WHERE id = ?", (value, item_id))
    conn.close()
    before = _cells(f.db)
    refused = f.cli("board", "import-review-candidates", str(REPORT), "--goal", "review")
    assert refused.exit_code == 1
    assert _last_line(refused) == f"Error: review-candidate provenance collision for item {item_id}"
    assert _cells(f.db) == before
