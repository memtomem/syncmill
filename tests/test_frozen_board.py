def _show_lines(item: dict, transitions: list[dict]) -> list[str]:
    """Every line `board show` must print for a released item, written out from
    the release's read and the documented field labels, not from render_item."""
    lines = [
        f"id:       {item['id']}",
        f"state:    {item['state']}",
        f"goal:     {item['goal'] or '-'}",
        f"task:     {item['task']}",
        f"owner:    {item['owner_agent'] or '-'}",
    ]
    for label, key in (("depends:  ", "depends_on"), ("inputs:   ", "inputs"),
                       ("outputs:  ", "outputs")):
        if item[key]:
            lines.append(label + ", ".join(item[key]))
    if item["handoff"]:
        lines.append(f"handoff:  {item['handoff']}")
    if item["human_required"]:
        lines.append("human:    REQUIRED")
    if item["blocked_reason"]:
        lines.append(f"blocked:  {item['blocked_reason']}")
    if item["evidence"]:
        lines.append("evidence:")
        for e in item["evidence"]:
            by = f" (by {e['by']})" if e["by"] else ""
            lines.append(f"  - [{e['kind']}/{'pass' if e['passed'] else 'fail'}] {e['ref']}{by}")
    if transitions:
        lines.append("history:")
        for t in transitions:
            note = f" — {t['note']}" if t["note"] else ""
            lines.append(f"  {t['from_state'] or '·'} → {t['to_state']}  "
                         f"[{t['actor'] or '?'}]{note}")
    return lines


def _printable(text: str) -> str:
    # The one escape the released rows need: a multi-line failure reason is one
    # display line (printable_name shows LF as the four characters \x0a).
    return text.replace("\n", "\\x0a")


