def test_every_release_freezes_every_scenario(tmp_path):
    # A release directory that lost a scenario, or a scenario that lost the
    # shape it was frozen for, would silently shrink coverage.
    assert RELEASES == ["v0.1.2", "v0.2.0", "v0.3.0"]
    for release in RELEASES:
        bindings = _bindings(release)
        assert bindings["release"] == release[1:]
        assert sorted(bindings["scenarios"]) == SCENARIOS[release]
        for scenario, facts in bindings["scenarios"].items():
            source = FROZEN / release / scenario
            assert sorted(p.name for p in source.iterdir()) == facts["files"]
            assert ("board.db-wal" in facts["files"]) == (scenario == "running"), scenario
            # A normal connection on a copy WITH the sidecars: an immutable
            # read of the original would not see rows still in the WAL.
            scratch = tmp_path / release / scenario
            shutil.copytree(source, scratch)
            tables, indexes = _schema(scratch / "board.db")
            assert tables == TABLES[release], (release, scenario)
            assert indexes == INDEXES[release], (release, scenario)
            conn = sqlite3.connect(scratch / "board.db")
            conn.row_factory = sqlite3.Row
            ids = {r["id"] for r in conn.execute("SELECT id FROM work_items")}
            assert ids == set(facts["release_read"]["items"]) == set(facts["items"].values())
            if scenario == "running":
                # The killed claim's lease and its ledger row, written in one
                # transaction and never purged (the run never finished).
                item = conn.execute("SELECT * FROM work_items WHERE id = ?",
                                    (facts["items"]["killed"],)).fetchone()
                ledger = conn.execute("SELECT * FROM board_run_namespaces WHERE run_id = ?",
                                      (item["lease_run_id"],)).fetchall()
                assert item["state"] == "running" and item["lease_run_id"]
                assert [(r["item_id"], r["claimed_at"], r["purged_at"]) for r in ledger] == [
                    (item["id"], item["claimed_at"], None)]
            conn.close()


