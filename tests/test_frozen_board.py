@pytest.mark.parametrize(("release", "scenario"), CASES)
def test_get_reads_every_released_item_as_the_release_did(release, scenario, frozen):
    f = frozen(release, scenario)
    board = f.board()
    try:
        expected = [f.read["items"][i] for i in f.read["order"]]
        assert plain(board.list()) == expected
        for state in WorkState:
            assert plain(board.list(state=state.value)) == \
                [i for i in expected if i["state"] == state.value], state
        for goal in sorted({i["goal"] for i in expected}):
            assert plain(board.list(goal=goal)) == [i for i in expected if i["goal"] == goal]
        for item_id, expected in f.read["items"].items():
            got = board.get(item_id)
            assert set(plain(got)) == set(expected), "WorkItem fields changed"
            assert plain(got) == expected, item_id
            assert board.transitions(item_id) == f.read["transitions"][item_id], item_id
    finally:
        board.close()
    # The raw cells too: the release read them the same way, but a stored
    # value has one meaning of its own (a scalar is passed through, a list
    # column is JSON, evidence is a JSON list of Evidence fields).
    board = f.board()
    try:
        for row in f.rows("SELECT * FROM work_items"):
            got = board.get(row["id"])
            for column in ("goal", "task", "owner_agent", "handoff", "blocked_reason",
                           "lease_run_id", "claimed_at", "created_at", "updated_at"):
                assert getattr(got, column) == row[column], (row["id"], column)
            assert got.state.value == row["state"]
            assert got.human_required is bool(row["human_required"])
            for column in ("inputs", "outputs", "depends_on"):
                assert getattr(got, column) == json.loads(row[column]), (row["id"], column)
            assert [dataclasses.asdict(e) for e in got.evidence] == json.loads(row["evidence"])
    finally:
        board.close()


