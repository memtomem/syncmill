#: scenario -> the revision HEAD's close leaves, the workspace being absent.
CLOSED_AT = {
    "open": 3, "checkpointed": 4, "closed": 4, "creating": 1, "closing": 3,
    "recovery-required": 4,
}


@pytest.mark.parametrize("scenario", list(SCENARIOS))
def test_close_a_released_session(release, scenario, tmp_path, monkeypatch, no_tmux):
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    before = frozen.document()
    result = frozen.cli("session", "close", frozen.session_id)
    assert result.exit_code == 0, result.output
    assert result.stdout.splitlines() == [f"Closed isolated session {frozen.session_id}"]
    after = frozen.document()
    assert (after["state"], after["revision"]) == ("closed", CLOSED_AT[scenario])
    if scenario == "closed":
        assert after == before
    else:
        # The lifecycle fields move; the checkpoints and bindings never do.
        moving = {"state", "revision", "updated_at"}
        assert {k: v for k, v in after.items() if k not in moving} == {
            k: v for k, v in before.items() if k not in moving
        }
    assert no_tmux.commands == []  # no process to kill: nothing was sent to tmux


# ── the checkpoint run artifact ───────────────────────────────────────────


def _checkpoint(frozen: Frozen) -> tuple[str, Path]:
    [run_id] = frozen.facts["checkpoints"]
    return run_id, frozen.project_dir / "runs" / run_id


@pytest.mark.parametrize("scenario", ["checkpointed", "closed"])
def test_a_released_checkpoint_reads_as_written(release, scenario, tmp_path, monkeypatch, no_tmux):
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    run_id, run_dir = _checkpoint(frozen)
    manifest = json.loads((run_dir / "manifest.json").read_text())
    assert manifest["state"] == "pending"
    assert manifest["plan"] == {"origin": "isolated-session", "session_id": frozen.session_id}
    listed = frozen.cli("runs", "list")
    assert listed.exit_code == 0, listed.output
    assert any(line.split()[:1] == [run_id] for line in listed.output.splitlines())
    shown = frozen.cli("runs", "show", run_id)
    assert shown.exit_code == 0, shown.output
    assert json.loads(shown.stdout) == manifest
    diff = frozen.cli("diff", run_id)
    assert diff.exit_code == 0, diff.output
    assert diff.stdout == (run_dir / "winner.patch").read_text()
    assert "+    return a + b" in diff.stdout
    conversation = frozen.cli("conversations", "show", run_id)
    assert conversation.exit_code == 0, conversation.output
    assert json.loads(conversation.stdout) == {
        "manifest": manifest, "result": json.loads((frozen.dir / "runs" / run_id / "result.json")
                                                   .read_text()),
    }
    # No provider session: not a conversation, and not continuable.
    conversations = frozen.cli("conversations", "list")
    assert conversations.exit_code == 0, conversations.output
    assert run_id not in conversations.output
    continued = frozen.cli("continue", run_id, "and more")
    assert (continued.exit_code, continued.output.splitlines()[-1]) == (
        1, "Error: run has no resumable provider session"
    )
    recovered = frozen.cli("recover", run_id)
    assert recovered.exit_code == 0, recovered.output
    assert recovered.output.splitlines() == [
        f"Run {run_id}: skipped \N{EM DASH} run is 'pending', not applying"
    ]
    assert frozen.document()["checkpoints"] == [run_id]


def test_the_tui_renders_a_released_checkpoint(release, tmp_path, monkeypatch, no_tmux):
    from syncmill.artifacts import ArtifactStore
    from syncmill.tui import _read_artifact_result, render_artifact

    frozen = Frozen(release, "checkpointed", tmp_path, monkeypatch)
