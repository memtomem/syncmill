def _edit(frozen: Frozen, **fields) -> None:
    path = frozen.project_dir / "sessions" / f"{frozen.session_id}.json"
    value = json.loads(path.read_text())
    value.update(fields)
    path.write_text(json.dumps(value, indent=2), encoding="utf-8")


@pytest.mark.parametrize("unsafe", ["workspace-root", "tmux-name", "worktree", "repository"])
def test_a_released_session_with_unsafe_paths_is_refused(
    release, unsafe, tmp_path, monkeypatch, no_tmux
):
    frozen = Frozen(release, "open", tmp_path, monkeypatch)
    # Cleanup and attachment are bound to paths and a name derived from the
    # session id; a document that disagrees is never acted on.
    if unsafe == "workspace-root":
        monkeypatch.setenv("SYNCMILL_WORKSPACE__ROOT", str(frozen.root / "elsewhere"))
    elif unsafe == "tmux-name":
        _edit(frozen, tmux_name="syncmill-p-someone-else")
    elif unsafe == "worktree":
        _edit(frozen, worktree_path=str(frozen.root / "elsewhere"))
    else:
        (frozen.root / "other").mkdir()
        other = _repo(frozen.root / "other", frozen.bindings["tree"])
        _edit(frozen, repo_root=str(other))
    before = frozen.document()
    assert frozen.store().list() == []
    result = frozen.cli("session", "checkpoint", frozen.session_id)
    error = (
        "session belongs to a different repository" if unsafe == "repository"
        else "session metadata contains unsafe paths"
    )
    assert (result.exit_code, result.output.splitlines()[-1]) == (1, f"Error: {error}")
    assert frozen.document() == before


