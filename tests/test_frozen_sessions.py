def test_attach_a_released_open_session(release, tmp_path, monkeypatch, no_tmux):
    frozen = Frozen(release, "open", tmp_path, monkeypatch)
    refused = frozen.cli("session", "attach-isolated", frozen.session_id)
    assert (refused.exit_code, refused.output.splitlines()[-1]) == (
        1, "Error: session process is no longer running"
    )
    assert no_tmux.attached == []

    # Running: its one pane must sit in the rebound worktree.
    no_tmux.live = True
    worktree = frozen.document()["worktree_path"]
    Path(worktree).mkdir(parents=True)

    def panes(*args, **kwargs):
        return subprocess.CompletedProcess(args, 0, stdout=worktree + "\n", stderr="")

    monkeypatch.setattr("syncmill.isolated_session._tmux", panes)
    attached = frozen.cli("session", "attach-isolated", frozen.session_id)
    assert attached.exit_code == 0, attached.output
    assert no_tmux.attached == [(frozen.document()["tmux_name"], "codex")]

    # A pane anywhere else is never attached to.
    monkeypatch.setattr("syncmill.isolated_session._PANE_CWD_SETTLE_SECONDS", 0)

    def elsewhere(*args, **kwargs):
        return subprocess.CompletedProcess(args, 0, stdout=str(frozen.root) + "\n", stderr="")

    monkeypatch.setattr("syncmill.isolated_session._tmux", elsewhere)
    refused = frozen.cli("session", "attach-isolated", frozen.session_id)
    assert refused.exit_code == 1, refused.output
    assert refused.output.splitlines()[-1] == (
        "Error: session cwd does not match its isolated workspace"
    )
    assert len(no_tmux.attached) == 1


