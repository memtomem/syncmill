def test_every_release_freezes_every_scenario():
    assert RELEASES == ["v0.1.2", "v0.2.0", "v0.3.0"]
    for release in RELEASES:
        bindings = _bindings(release)
        assert bindings["release"] == release.removeprefix("v")
        assert sorted(bindings["scenarios"]) == sorted(SCENARIOS)
        assert bindings["marker"]["mode"] == "0o600"
        for name, facts in bindings["scenarios"].items():
            assert (facts["state"], facts["revision"]) == SCENARIOS[name], (release, name)
            assert fingerprint_version(facts["source_fingerprint"]) == 1
            document = json.loads(next((FROZEN / release / name / "sessions").glob("*.json"))
                                  .read_text())
            assert document["schema_version"] == 1
            assert (document["state"], document["revision"]) == SCENARIOS[name]
            assert document["checkpoints"] == facts["checkpoints"]
            runs = sorted(p.name for p in (FROZEN / release / name / "runs").glob("*")) \
                if (FROZEN / release / name / "runs").is_dir() else []
            assert runs == sorted(facts["checkpoints"])
        project = FROZEN / release / "project"
        assert sorted(p.name for p in project.iterdir()) == [
            "marker.gitignore", "marker.json", "syncmill.toml"
        ]


