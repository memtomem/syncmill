@pytest.mark.parametrize("scenario", list(SCENARIOS))
def test_isolated_list_reads_a_released_session(release, scenario, tmp_path, monkeypatch, no_tmux):
    frozen = Frozen(release, scenario, tmp_path, monkeypatch)
    state, _ = SCENARIOS[scenario]
    listed = frozen.cli("session", "isolated-list")
    assert listed.exit_code == 0, listed.output
    [line] = listed.output.splitlines()
    assert line.split() == [frozen.session_id, "codex", state, "stopped"]

    # Live is the probe's answer; staleness is the stored fingerprint
    # recomputed in its own version, and only an open session is judged.
    no_tmux.live = True
    (frozen.repo / "calc.py").write_text(FIXED, encoding="utf-8")
    [value] = frozen.store().list()
    assert value["live"] is True
    assert value["source_stale"] is (state == "open")
    for field in PATH_FIELDS:
        assert value[field].startswith(str(frozen.root) + "/")


