"""Released isolated sessions and project markers, read by the current readers
(#271, persisted contracts D).

The documents under ``fixtures/persisted/sessions/<release>/`` were written
by that release's own ``syncmill init`` and ``syncmill session`` commands
(see ``freeze.py`` there) and are never regenerated by the current writer.
``project/`` holds what ``init`` wrote: ``syncmill.toml`` and the marker
directory's ``project.json`` and ``.gitignore``, stored as ``marker.json`` and
``marker.gitignore``. Every other scenario is one project: its session
document and any checkpoint run artifact. Workspaces were not frozen.

Only machine-bound values are rebound, each in a named place: a session
document's four paths (repository, workspace run root, control clone,
worktree) and its source fingerprint (recomputed in the stored value's own
version), and a checkpoint artifact's repository root and fingerprint. The
tmux name is derived from the project, agent and session id, so it is never
rebound. ``Frozen`` asserts every other byte is unchanged.

tmux is never launched: the store's probe and command seams and the CLI's
gates are patched.
"""

from __future__ import annotations

import json
import logging
import os
import subprocess
from pathlib import Path
from types import SimpleNamespace

import pytest
from click.testing import CliRunner

from syncmill.cli import cli
from syncmill.worktree import fingerprint_version, repository_fingerprint

FROZEN = Path(__file__).parent / "fixtures" / "persisted" / "sessions"
RELEASES = sorted(p.parent.name for p in FROZEN.glob("v*/bindings.json"))

#: scenario -> (state, revision) the release left its session in.
SCENARIOS = {
    "open": ("open", 1),
    "checkpointed": ("open", 2),
    "closed": ("closed", 4),
    "creating": ("creating", 0),
    "closing": ("closing", 2),
    "recovery-required": ("recovery_required", 3),
}
#: The four paths a session document binds to the generating machine.
PATH_FIELDS = ("repo_root", "run_root", "control_repo", "worktree_path")
FIXED = "def add(a, b):\n    return a + b\n"


def _bindings(release: str) -> dict:
    return json.loads((FROZEN / release / "bindings.json").read_text())


@pytest.fixture(params=RELEASES)
def release(request) -> str:
    return request.param


def _repo(root: Path, tree: dict) -> Path:
    """The generating repository's shape: the tree and ``syncmill.toml``
    committed, ``.syncmill/`` ignored."""
    repo = root / "repo"
    repo.mkdir()
    for name, text in tree.items():
        (repo / name).write_text(text, encoding="utf-8")
    for argv in (
        ["init", "-q"],
        ["add", "-A"],
        ["-c", "user.name=t", "-c", "user.email=t@t.test", "-c",
         "commit.gpgsign=false", "commit", "-q", "-m", "frozen tree"],
    ):
        subprocess.run(["git", *argv], cwd=repo, check=True, capture_output=True)
    (repo / ".git" / "info" / "exclude").write_text(".syncmill/\n", encoding="utf-8")
    return repo


class Frozen:
    """One release session scenario installed as a project bound to ``repo``."""

    def __init__(self, release: str, scenario: str, tmp_path: Path, monkeypatch):
        self.release = release
        self.scenario = scenario
        self.bindings = _bindings(release)
        self.facts = self.bindings["scenarios"][scenario]
        self.dir = FROZEN / release / scenario
        self.root = tmp_path.resolve()
        self.repo = _repo(self.root, self.bindings["tree"])
        self.session_id = self.facts["session_id"]
        self.runs_root = self.root / "state" / "runs"
        self.workspace_root = self.root / "state" / "workspaces"
        self.project_dir = self.runs_root / self.facts["project_id"]
        monkeypatch.setenv("SYNCMILL_RUNS__ROOT", str(self.runs_root))
        monkeypatch.setenv("SYNCMILL_WORKSPACE__ROOT", str(self.workspace_root))
        monkeypatch.setenv("SYNCMILL_PROJECT__ID", self.facts["project_id"])
        stored = self.facts["source_fingerprint"]
        self.fingerprint = repository_fingerprint(self.repo, like=stored)
        # Recomputed in the stored value's own version, never upgraded.
        assert fingerprint_version(self.fingerprint) == fingerprint_version(stored) == 1
        self._install()

    def _rebound(self, data: bytes, *, paths: int) -> bytes:
        stored = self.facts["source_fingerprint"].encode()
        box = self.bindings["box_root"].encode()
        assert data.count(stored) == 1
        assert data.count(box) == paths
        return data.replace(stored, self.fingerprint.encode()).replace(
            box, str(self.root).encode()
        )

    def _install(self) -> None:
        sessions = self.project_dir / "sessions"
        sessions.mkdir(parents=True)
        [document] = (self.dir / "sessions").glob("*.json")
        assert document.stem == self.session_id
        installed = sessions / document.name
        installed.write_bytes(self._rebound(document.read_bytes(), paths=len(PATH_FIELDS)))
        # Only the bound fields moved.
        released, now = json.loads(document.read_text()), json.loads(installed.read_text())
        bound = {*PATH_FIELDS, "source_fingerprint"}
        assert {k: v for k, v in now.items() if k not in bound} == {
            k: v for k, v in released.items() if k not in bound
        }
        if (self.dir / "runs").is_dir():
            import shutil

            shutil.copytree(self.dir / "runs", self.project_dir / "runs")
            for manifest in self.project_dir.glob("runs/*/manifest.json"):
                manifest.write_bytes(self._rebound(manifest.read_bytes(), paths=1))

    def document(self) -> dict:
        return json.loads(
            (self.project_dir / "sessions" / f"{self.session_id}.json").read_text()
        )

    def released(self) -> dict:
        [document] = (self.dir / "sessions").glob("*.json")
        return json.loads(document.read_text())

    def store(self):
        from syncmill.isolated_session import IsolatedSessionStore
        from syncmill.project import load_project_config

        _, config = load_project_config(self.repo)
        return IsolatedSessionStore(config, self.repo)

    def cli(self, *argv: str):
        return CliRunner().invoke(cli, [*argv, "--repo", str(self.repo)])


@pytest.fixture
def no_tmux(monkeypatch):
    """No real tmux anywhere: the store's probe and commands, the CLI's gates
    and attachment. ``live`` says what the probe answers."""
    state = SimpleNamespace(live=False, attached=[], commands=[])

    def tmux(*args, **kwargs):
        state.commands.append(args)
        return subprocess.CompletedProcess(args, 0, stdout="", stderr="")

    monkeypatch.setattr("syncmill.isolated_session.session_exists", lambda name: state.live)
    monkeypatch.setattr("syncmill.isolated_session._tmux", tmux)
    monkeypatch.setattr(
        "syncmill.isolated_session._attach_and_report",
        lambda name, agent: state.attached.append((name, agent)) or 0,
    )
    monkeypatch.setattr("syncmill.cli.tmux_available", lambda: True)
    monkeypatch.setattr("syncmill.cli._stdout_isatty", lambda: True)
    return state


